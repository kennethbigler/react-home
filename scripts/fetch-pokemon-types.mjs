#!/usr/bin/env node
/**
 * Fetches Pokémon type matchups for every generation from PokéAPI and writes
 * them to src/constants/pokemon-type-charts.ts for the /games/types grid.
 *
 * Each type's `past_damage_relations` entry holds the relations that applied
 * up to and including its `generation`; later generations use the current
 * `damage_relations`. Only the attacking side (`*_damage_to`) is read.
 *
 * Usage: node scripts/fetch-pokemon-types.mjs
 *   or:  npm run fetch-pokemon-types
 */

import { writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = join(__dirname, "../src/constants/pokemon-type-charts.ts");
const API_BASE = "https://pokeapi.co/api/v2";

// must match the order of `types` in src/constants/type-checker.ts
const TYPE_NAMES = [
  "normal",
  "fighting",
  "flying",
  "poison",
  "ground",
  "rock",
  "bug",
  "ghost",
  "steel",
  "fire",
  "water",
  "grass",
  "electric",
  "psychic",
  "ice",
  "dragon",
  "dark",
  "fairy",
];

const getJson = async (path) => {
  const res = await fetch(`${API_BASE}/${path}`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  return res.json();
};

/** "https://pokeapi.co/api/v2/generation/3/" -> 3 */
const idFromUrl = (url) => Number(url.split("/").filter(Boolean).pop());

/** one attacking row of multipliers against every defending type */
const toRow = (relations) =>
  TYPE_NAMES.map((name) => {
    const has = (key) => relations[key].some((t) => t.name === name);
    if (has("no_damage_to")) return 0;
    if (has("half_damage_to")) return 0.5;
    if (has("double_damage_to")) return 2;
    return 1;
  });

/** relations in effect for `gen`: earliest past entry still covering it */
const relationsFor = (type, gen) => {
  const past = type.past_damage_relations
    .map((p) => ({ gen: idFromUrl(p.generation.url), rel: p.damage_relations }))
    .filter((p) => p.gen >= gen)
    .sort((a, b) => a.gen - b.gen);
  return past.length ? past[0].rel : type.damage_relations;
};

const main = async () => {
  const { count: latest } = await getJson("generation");
  const apiTypes = await Promise.all(TYPE_NAMES.map((n) => getJson(`type/${n}`)));
  const introduced = apiTypes.map((t) => idFromUrl(t.generation.url));

  // group consecutive generations that share an identical chart
  const charts = [];
  for (let gen = 1; gen <= latest; gen += 1) {
    const effectiveness = apiTypes.map((t) => toRow(relationsFor(t, gen)));
    const prev = charts[charts.length - 1];
    if (prev && JSON.stringify(prev.effectiveness) === JSON.stringify(effectiveness)) {
      prev.to = gen;
    } else {
      charts.push({ from: gen, to: gen, effectiveness });
    }
  }

  const rows = (eff) =>
    eff.map((row, i) => `      // ${TYPE_NAMES[i]}\n      [${row.join(", ")}],`).join("\n");
  const body = charts
    .map(
      (c) =>
        `  {\n    from: ${c.from},\n    to: ${c.to},\n    effectiveness: [\n${rows(c.effectiveness)}\n    ],\n  },`,
    )
    .join("\n");

  const file = `// Generated by scripts/fetch-pokemon-types.mjs from PokéAPI. Do not edit by hand.
import type { Effectiveness } from "./type-checker";

interface TypeChart {
  from: number;
  to: number;
  effectiveness: Effectiveness[][];
}

/** latest generation PokéAPI knows about */
export const LATEST_GENERATION = ${latest};

/** generation each type was introduced, in \`types\` order */
export const TYPE_INTRODUCED = [${introduced.join(", ")}];

/** attacker (row) vs defender (column) multipliers, by generation range */
export const TYPE_CHARTS: TypeChart[] = [
${body}
];
`;

  writeFileSync(OUTPUT_PATH, file);
  console.log(`Wrote ${charts.length} charts (gens 1-${latest}) to ${OUTPUT_PATH}`);
};

await main();
